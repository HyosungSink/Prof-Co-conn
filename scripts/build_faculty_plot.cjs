const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const context = vm.createContext({ URL });
for (const asset of [
  'data', 'faculty-data', 'faculty-titles', 'faculty-rosters',
  'faculty-bibliography', 'faculty-ucas-institutes', 'faculty-catalog', 'faculty-title-values',
]) {
  vm.runInContext(fs.readFileSync(path.join(root, asset + '.js'), 'utf8'), context, { filename: asset + '.js' });
}
const stats = vm.runInContext('const catalog = buildFacultyCatalog(); summarizeFaculty(catalog)', context);
const { people, titles } = vm.runInContext(`(() => {
  const titles = new Map();
  // The first recorded title keeps the chart at exactly one tile per record.
  function titleIndex(person) {
    const [title] = facultyTitleValues(person);
    if (!titles.has(title)) titles.set(title, titles.size);
    return titles.get(title);
  }
  const people = Object.fromEntries(Object.entries(catalog).map(([school, units]) => [
    school, Object.fromEntries(units.map(unit => [unit.name, unit.people.map(person => [
      person.name, facultyVerification(person, school, unit.name), titleIndex(person)
    ]).sort((a, b) => b[1] - a[1])]))
  ]));
  return { people, titles: [...titles.keys()] };
})()`, context);
const output = '// Generated by scripts/build_faculty_plot.cjs. Each row is [school, total, complete, units].\n' +
  '// Unit fields: [name, [[person, number of verified fields, title index], ...]].\n' +
  'const facultyPlotTitles = ' + JSON.stringify(titles) + ';\n' +
  'const facultyPlotStats = [\n' +
  stats.map(({ name, count, complete, units }) =>
    '  ' + JSON.stringify([name, count, complete, units.map(unit => [unit.name, people[name][unit.name]])]) + ','
  ).join('\n') +
  '\n];\n';
const target = path.join(root, 'faculty-plot-data.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) {
    console.error('Faculty plot data is outdated. Run python3 scripts/version_assets.py to update it.');
    process.exitCode = 1;
  }
} else if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
  fs.writeFileSync(target, output);
}
