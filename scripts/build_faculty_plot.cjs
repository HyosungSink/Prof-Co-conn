const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const context = vm.createContext({ URL });
for (const asset of [
  'data', 'faculty-data', 'faculty-titles', 'faculty-rosters',
  'faculty-bibliography', 'faculty-ucas-institutes', 'faculty-catalog',
]) {
  vm.runInContext(fs.readFileSync(path.join(root, asset + '.js'), 'utf8'), context, { filename: asset + '.js' });
}
const stats = vm.runInContext('summarizeFaculty(buildFacultyCatalog())', context);
const output = '// Generated by scripts/build_faculty_plot.cjs. Each row is [school, total, complete].\n' +
  'const facultyPlotStats = [\n' +
  stats.map(({ name, count, complete }) => '  ' + JSON.stringify([name, count, complete]) + ',').join('\n') +
  '\n];\n';
const target = path.join(root, 'faculty-plot-data.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output) {
    console.error('Faculty plot data is outdated. Run python3 scripts/version_assets.py to update it.');
    process.exitCode = 1;
  }
} else if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
  fs.writeFileSync(target, output);
}
